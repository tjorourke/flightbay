package collect

import (
	"fmt"
	"sort"
	"strings"

	"github.com/tjorourke/flightbay/internal/flows"
	"github.com/tjorourke/flightbay/internal/policy"
	"github.com/tjorourke/flightbay/internal/redact"
)

// sampleImages are representative images for each component detect()
// recognises; the document lists what is read from each.
var sampleImages = []struct{ label, container, image string }{
	{"ztunnel", "istio-proxy", "docker.io/istio/ztunnel:1.30"},
	{"Envoy (sidecars, Istio gateways and waypoints)", "istio-proxy", "docker.io/istio/proxyv2:1.30"},
	{"agentgateway (gateways and waypoints)", "agentgateway", "cr.agentgateway.dev/agentgateway:1.0"},
	{"istiod", "discovery", "docker.io/istio/pilot:1.30"},
	{"agentgateway and kgateway controllers", "controller", "example/enterprise-agentgateway-controller:1"},
}

// InventoryMarkdown renders "what Flightbay collects and what it never
// collects" from the collector's own tables, so the document cannot drift
// from the code. docs/COLLECTS.md is this output; a test keeps them equal.
func InventoryMarkdown() string {
	var b strings.Builder
	w := func(f string, a ...any) { fmt.Fprintf(&b, f, a...) }
	w("# What Flightbay collects, and what it never collects\n\n")
	w("Generated by `flightbay docs collects` from the collector's own tables. Do not edit by hand.\n\n")
	w("Flightbay collects only what the collection policy selects. You choose the policy before anything is read: a profile, a config file (`--config`), flags, or `collect --interactive`. Run `flightbay collect --dry-run` to see the resolved selection and the RBAC it needs; a dry run reads API discovery only. The bundle is written locally; uploading is a separate step.\n\n")

	w("## Never collected\n\n")
	w("- **Secret values.** Secrets are reduced to name, namespace, type, labels, annotations (without `last-applied-configuration`), owner references and, with `--secrets keys`, key names and byte lengths. With `--secrets metadata` the Secret body is never requested (metadata API). `--secrets omit` skips Secrets entirely.\n")
	w("- **Helm values.** Helm release Secrets are reduced to chart name, version, app version, status and revision.\n")
	w("- **`managedFields`** on any object.\n")
	w("- **Envoy SDS secret sections** of proxy config dumps. Certificate details for expiry checks come from `/certs`, which contains no keys.\n")
	w("- **Controller krt snapshots.** The agentgateway and kgateway admin snapshot spans every namespace and can hold Secret contents, so it is never read.\n")
	w("- **Anything from namespaces outside the selection**, including inside proxy and control-plane dumps: entries that name other namespaces are removed before the bundle is written.\n")
	w("- **Anything a policy exclusion covers**, through any collector. If a diagnostic endpoint would expose an excluded resource type, it is skipped and the reason recorded.\n\n")

	w("## Profiles\n\n| Profile | Categories | Object detail | ConfigMaps | Secrets | Logs |\n|---|---|---|---|---|---|\n")
	for _, name := range []string{"minimal", "standard", "custom"} {
		p, _ := policy.Profile(name)
		var cats []string
		for _, c := range p.Categories {
			cats = append(cats, string(c))
		}
		logs := "not collected"
		if p.Has(policy.CatLogs) {
			logs = fmt.Sprintf("%s streams, last %s, up to %d MiB per stream (newest kept)", strings.Join(p.Logs.Streams, " and "), p.Logs.Since, p.Logs.MaxBytes>>20)
		}
		if len(cats) == 0 {
			cats = []string{"none until you choose"}
		}
		w("| %s | %s | %s | %s | %s | %s |\n", name, strings.Join(cats, ", "), p.ObjectDetail, p.ConfigMaps, p.Secrets, logs)
	}
	w("\nCluster-scoped objects (nodes, CRDs, ClusterRoles) need `--cluster-scoped`. Proxy dumps, control-plane debug output and metrics need `--solo-diagnostics` (or the categories plus `--portforward`).\n\n")

	w("## Categories\n\n| Category | What is read |\n|---|---|\n")
	w("| objects | `list` of each selected resource type in the selected namespaces, in bounded chunks. CRD definitions of selected custom resources (names and printer columns; the schema is dropped). |\n")
	w("| events | `events.k8s.io/v1` and core events in the selected namespaces. |\n")
	w("| logs | `pods/log` for selected containers with `timestamps=true`, within the time window and per-stream byte limit. |\n")
	w("| nodes | Node objects: conditions, capacity, versions, taints (needs `--cluster-scoped`). |\n")
	w("| helm | Chart summaries from Helm release Secrets (needs `--secrets keys`). |\n")
	w("| proxies, control-plane, metrics | Admin endpoints of Solo components among the selected pods, through port-forward. See below. |\n\n")

	w("## Diagnostic endpoints (port-forward)\n\nRead only from pods in the selected namespaces, only when port-forward is allowed. Every response is filtered to the selected namespaces and scrubbed before it is written.\n\n")
	w("| Component | Category | Port | Path | Skipped when excluded |\n|---|---|---|---|---|\n")
	for _, si := range sampleImages {
		comps := detect(podInfo{containers: []containerInfo{{name: si.container, image: si.image}}, images: map[string]string{si.container: si.image}})
		for _, c := range comps {
			for _, ep := range c.endpoints {
				var needs []string
				for _, r := range ep.needs {
					needs = append(needs, r.resource)
				}
				var strips []string
				for k, r := range ep.strip {
					strips = append(strips, fmt.Sprintf("`%s` removed if %s excluded", k, r.resource))
				}
				sort.Strings(strips)
				note := strings.Join(append(needs, strips...), "; ")
				if ep.envoy {
					note = strings.TrimPrefix(note+"; SDS secrets always removed", "; ")
				}
				if ep.perEntry {
					note = strings.TrimPrefix(note+"; each object checked against the resource, namespace and cluster-scoped selection", "; ")
				}
				if ep.nsKeyed {
					note = strings.TrimPrefix(note+"; entries for other namespaces removed", "; ")
				}
				w("| %s | %s | %d | `%s` | %s |\n", si.label, ep.cat, ep.port, ep.path, note)
			}
			for _, n := range c.notes {
				w("| %s | | | | Not read: %s |\n", si.label, n)
			}
		}
	}

	w("\n## Observed traffic (flows)\n\n")
	w("Who actually called whom comes from logs already selected above, plus optional flow logs. Nothing extra is read from the cluster unless you ask for it.\n\n")
	w("| Source | Where it comes from | Notes |\n|---|---|---|\n")
	w("| ztunnel | ztunnel access logs (`access`, `http_access`) | Counted once per connection even when both ends log it. |\n")
	w("| agentgateway | agentgateway request logs (scope `request`, text or JSON) | Route, gateway, backend endpoint, `jwt.sub`, MCP method and tool, A2A method, LLM provider. 401 and 403 count as denied. |\n")
	w("| envoy | `istio-proxy` access logs of sidecars, Istio gateways and waypoints (Istio's default text format or its JSON encoding) | Upstream cluster gives the destination; RBAC, ext_authz, 401/403 and BlackHoleCluster count as denied. |\n")
	w("| coredns | CoreDNS query logs | External names only: in-cluster names, reverse lookups and search-path expansions are skipped. The CoreDNS `log` plugin is **off by default**; add `log` to the Corefile for these to exist. |\n")
	w("| %s | `flightbay collect --attach-flows FILE[@CONTEXT]` | Customer-supplied flow logs embedded under `clusters/<context>/flows/<format>/<file>` and covered by the manifest. Records naming namespaces outside the selection are removed and every line is redacted before writing. |\n", strings.Join(flows.Formats, ", "))
	w("| hubble (live) | `flightbay collect --hubble-flows[=N]` (default N = 20000) | Port-forward to the `hubble-relay` pod in `%s` (port %d) and run the local `hubble observe --last N -o jsonpb`, with `--namespace` for each selected namespace. Needs port-forward, `pods` get/list and `pods/portforward` create in `%s`, and the `hubble` CLI on PATH; the dry run says whether it was found. Flows naming namespaces outside the selection are removed and HTTP paths redacted before writing. |\n\n", policy.HubbleNamespace, hubbleRelayPort, policy.HubbleNamespace)
	w("Flow files can also be added when a bundle is opened (`flightbay-desk open BUNDLE --flows FILE[@CLUSTER]`); those are marked as added by the reviewer and are not part of the signed bundle.\n\n")
	w("Supported flow log formats, detected per file: Cilium Hubble (`hubble observe -o json` or `-o jsonpb`), Calico Enterprise / Cloud flow logs (JSON), AWS VPC flow logs (default version 2 format, or a custom format with a header line), GCP VPC flow logs and firewall logs (Cloud Logging JSON export, as JSON Lines or an array), Azure NSG and VNet flow logs (JSON), and a generic CSV or JSON Lines file with any of these columns: `src_ip|source_ip|srcaddr`, `dst_ip|dest_ip|dstaddr`, `dst_port|dest_port|dstport`, `src_namespace`, `src_pod`, `dst_namespace`, `dst_pod`, `dst_host|dest_domain|fqdn`, `protocol|proto`, `method`, `path`, `action|verdict`, `count|packets`. The generic form is the way in for any other CNI or firewall (Antrea, Weave, kube-router, a firewall export or a SIEM query).\n")

	w("\n## Redaction\n\nRuns in memory before anything is written, over object specs, ConfigMap data, environment variables, log lines and diagnostic output:\n\n")
	for _, r := range redact.Rules {
		w("- `%s`: %s\n", r.Name, r.Description)
	}
	w("- your own patterns from `--redact-extra` (one Go regular expression per line)\n")
	w("- fields you name with `--drop-field PATH` or `dropFields` in a config file, removed from every object, e.g. `metadata.annotations[\"corp.example/*\"]`\n\n")
	w("JSON held inside a string, such as the `kubectl.kubernetes.io/last-applied-configuration` annotation or a JSON file in a ConfigMap, is parsed and redacted with the same rules, so an environment variable or key inside an embedded manifest is caught too.\n\n")
	w("`redaction-report.json` in the bundle records how many replacements were made in each file, never the values. Review it with `flightbay inspect BUNDLE --redactions` before sending.\n\n")

	w("## In every bundle\n\n")
	w("- `bundle.json` (first): identity, case, contexts, capture start and the resolved collection policy.\n")
	w("- `collection-log.jsonl`: every call, including failures (RBAC denied, timeouts, truncation), so a missing file never looks like a missing object.\n")
	w("- `coverage/*.json`: per collection, what was expected and whether it completed, failed, was excluded or truncated. Attached and hubble flow files have a `flows` coverage entry each, with the detected format.\n")
	w("- `manifest.json`: capture end, completion state and a SHA-256 for every member. `flightbay inspect` verifies them.\n")
	w("- `manifest.sig` (last, with `--sign KEY`): your Ed25519 signature over the manifest, so Solo can check the bundle came from you unmodified. Solo only ever holds your public key.\n")
	w("- The SHA-256 of the collector binary, and with `--config` the policy file's SHA-256 and who approved it (`flightbay policy sign`).\n\n")
	w("Before sending, `flightbay review BUNDLE` lets you remove namespaces, resource types, objects, log streams, log lines and files and redact more, then exports a new signed bundle with `review-ledger.json`, a count of what you removed.\n\n")
	w("The bundle is a plain tar stream compressed with zstd. Open it with standard tools: `tar --zstd -tvf BUNDLE`. With `--encrypt-to` it is wrapped in age encryption and only the holder of the matching identity can read it.\n")
	return b.String()
}
