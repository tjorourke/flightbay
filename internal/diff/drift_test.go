var (
	rDep = bundle.APIResource{Group: "apps", Version: "v1", Resource: "deployments", Kind: "Deployment", Namespaced: true}
	rSvc = bundle.APIResource{Version: "v1", Resource: "services", Kind: "Service", Namespaced: true}
	rCM  = bundle.APIResource{Version: "v1", Resource: "configmaps", Kind: "ConfigMap", Namespaced: true}
	rSA  = bundle.APIResource{Version: "v1", Resource: "serviceaccounts", Kind: "ServiceAccount", Namespaced: true}
)

func dep(name string, replicas float64, image string, live bool) map[string]any {
	ct := map[string]any{"name": "web", "image": image}
	ps := map[string]any{"containers": []any{ct}}
	d := map[string]any{"apiVersion": "apps/v1", "kind": "Deployment",
		"metadata": map[string]any{"name": name, "namespace": "demo", "labels": map[string]any{"app": name}},
		"spec": map[string]any{"replicas": replicas, "selector": map[string]any{"matchLabels": map[string]any{"app": name}},
			"template": map[string]any{"metadata": map[string]any{"labels": map[string]any{"app": name}}, "spec": ps}}}
	if live {
		md := d["metadata"].(map[string]any)
		md["uid"], md["resourceVersion"], md["generation"], md["creationTimestamp"] = "u-1", "123", float64(4), "2026-09-01T00:00:00Z"
		md["annotations"] = map[string]any{"deployment.kubernetes.io/revision": "3", "kubectl.kubernetes.io/last-applied-configuration": "{}"}
		md["managedFields"] = []any{map[string]any{"manager": "kubectl"}}
		sp := d["spec"].(map[string]any)
		sp["revisionHistoryLimit"], sp["progressDeadlineSeconds"] = float64(10), float64(600)
		sp["strategy"] = map[string]any{"type": "RollingUpdate"}
		ps["dnsPolicy"], ps["schedulerName"], ps["restartPolicy"], ps["terminationGracePeriodSeconds"] = "ClusterFirst", "default-scheduler", "Always", float64(30)
		ps["securityContext"] = map[string]any{}
		ct["imagePullPolicy"], ct["terminationMessagePath"], ct["terminationMessagePolicy"] = "IfNotPresent", "/dev/termination-log", "File"
		ct["resources"] = map[string]any{}
		d["status"] = map[string]any{"replicas": replicas, "readyReplicas": replicas}
	}
	return d
}

func named(kind, name string, extra map[string]any) map[string]any {
	o := map[string]any{"apiVersion": "v1", "kind": kind, "metadata": map[string]any{"name": name, "namespace": "demo"}}
	for k, v := range extra {
		o[k] = v
	}
	return o
}

func workspace(declared bool, cluster string) *store.Workspace {
	ws := store.New()
	h := &bundle.Header{Contexts: []string{cluster}}
	if declared {
		h.Source, h.Repo = bundle.SourceRepo, &bundle.RepoInfo{Name: "sample", Commit: "abc1234def"}
	}
	ws.SetHeader(h)
	for _, r := range []bundle.APIResource{rDep, rSvc, rCM, rSA} {
		ws.SetCoverage(bundle.Coverage{ID: cluster + "." + r.Resource, Cluster: cluster, Type: bundle.CoverageResource, Group: r.Group, Version: r.Version, Resource: r.Resource, State: bundle.StateComplete})
	}
	ws.SetState(func(s *store.ImportState) { s.Phase = store.PhaseComplete; s.Verified = true })
	return ws
}

func TestDrift(t *testing.T) {
	repo := workspace(true, "repo_sample")
	web := dep("web", 2, "nginx:1.27", false)
	web["metadata"].(map[string]any)["annotations"] = map[string]any{"flightbay.dev/source": "k8s/app.yaml", "flightbay.dev/source-line": "9"}
	repo.AddObjects("repo_sample", rDep, []map[string]any{web, dep("api", 1, "api:1", false), dep("gone", 1, "gone:1", false)}, "d")
	repo.AddObjects("repo_sample", rSvc, []map[string]any{named("Service", "web", map[string]any{"spec": map[string]any{"selector": map[string]any{"app": "web"}, "ports": []any{map[string]any{"port": float64(80)}}}})}, "s")

	live := workspace(false, "kind-flightbay-scan")
	liveWeb := dep("web", 2, "nginx:1.27", true)
	liveAPI := dep("api", 1, "api:1", true)
	liveAPI["spec"].(map[string]any)["replicas"] = float64(3) // scaled by hand
	live.AddObjects("kind-flightbay-scan", rDep, []map[string]any{liveWeb, liveAPI, dep("hand", 1, "hand:1", true)}, "d")
	live.AddObjects("kind-flightbay-scan", rSvc, []map[string]any{named("Service", "web", map[string]any{"spec": map[string]any{"selector": map[string]any{"app": "web"},
		"ports": []any{map[string]any{"port": float64(80), "protocol": "TCP", "targetPort": float64(80)}}, "clusterIP": "10.96.0.10", "clusterIPs": []any{"10.96.0.10"},
		"type": "ClusterIP", "sessionAffinity": "None", "ipFamilies": []any{"IPv4"}, "ipFamilyPolicy": "SingleStack", "internalTrafficPolicy": "Cluster"}})}, "s")
	// generated by the cluster: never "in the cluster, not in Git"
	live.AddObjects("kind-flightbay-scan", rCM, []map[string]any{named("ConfigMap", "kube-root-ca.crt", nil)}, "c")
	live.AddObjects("kind-flightbay-scan", rSA, []map[string]any{named("ServiceAccount", "default", nil)}, "sa")

	r := Drift(repo, live)
	if len(r.Differs) != 1 || r.Differs[0].Name != "api" {
		t.Fatalf("differs = %+v, want only api (defaulted fields and server metadata ignored)", r.Differs)
	}
	f := r.Differs[0].Fields
	if len(f) != 1 || f[0].Path != "spec.replicas" || f[0].Declared != "1" || f[0].Live != "3" {
		t.Errorf("api fields = %+v, want spec.replicas 1 -> 3", f)
	}
	if len(r.InGitOnly) != 1 || r.InGitOnly[0].Name != "gone" {
		t.Errorf("in Git only = %+v, want gone", r.InGitOnly)
	}
	if len(r.InClusterOnly) != 1 || r.InClusterOnly[0].Name != "hand" {
		t.Errorf("in cluster only = %+v, want hand (and not kube-root-ca.crt or the default ServiceAccount, whose kinds Git does not declare)", r.InClusterOnly)
	}
	if r.Same != 2 {
		t.Errorf("same = %d, want 2 (web Deployment and Service)", r.Same)
	}
	if r.Labels != [2]string{DeclaredLabel, LiveLabel} || r.Declared.Repo != "sample@abc1234def" {
		t.Errorf("labels %v repo %q", r.Labels, r.Declared.Repo)
	}
	txt := r.Text()
	for _, want := range []string{"In Git, not in the cluster:", "In the cluster, not in Git:", "Differs:", "spec.replicas: 1 -> 3"} {
		if !strings.Contains(txt, want) {
			t.Errorf("text has no %q:\n%s", want, txt)
		}
	}

	// A field the repo sets is compared even when it is in the defaulted list.
	web2 := dep("web", 2, "nginx:1.27", false)
	web2["spec"].(map[string]any)["template"].(map[string]any)["spec"].(map[string]any)["dnsPolicy"] = "None"
	repo2 := workspace(true, "repo_sample")
	repo2.AddObjects("repo_sample", rDep, []map[string]any{web2}, "d")
	r2 := Drift(repo2, live)
	if len(r2.Differs) != 1 || r2.Differs[0].Fields[0].Path != "spec.template.spec.dnsPolicy" {
		t.Errorf("declared dnsPolicy should be compared: %+v", r2.Differs)
	}

	// Compare (the desk's baseline view) reports the drift with labelled sides.
	c := Compare(repo, live)
	if c.Drift == nil || c.Before.Label != DeclaredLabel || c.After.Label != LiveLabel || c.Summary["changed"] != 1 || c.Summary["added"] != 1 || c.Summary["removed"] != 1 {
		t.Errorf("Compare with a repo scan = %+v", c.Summary)
	}
	if c2 := Compare(live, repo); c2.Drift == nil || c2.Before.Label != DeclaredLabel {
		t.Error("the repo scan is the declared side whichever way round it is passed")
	}
}

func TestQuantitiesCompareByValue(t *testing.T) {
	a := map[string]any{"spec": map[string]any{"template": map[string]any{"spec": map[string]any{"containers": []any{map[string]any{"name": "c", "resources": map[string]any{"requests": map[string]any{"cpu": "0.5", "memory": "1Gi"}}}}}}}}
	b := map[string]any{"spec": map[string]any{"template": map[string]any{"spec": map[string]any{"containers": []any{map[string]any{"name": "c", "resources": map[string]any{"requests": map[string]any{"cpu": "500m", "memory": "1024Mi"}}}}}}}}
	if f := compareDeclared(a, b); len(f) != 0 {
		t.Errorf("equal quantities reported as drift: %+v", f)
	}
}
