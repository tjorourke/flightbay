#!/usr/bin/env python3
"""Generate the macOS Homebrew formula from published, checksummed archives."""

import argparse
from pathlib import Path
import re
from urllib.request import urlopen


def checksum(url, name):
    with urlopen(url, timeout=60) as response:
        text = response.read(1024 * 1024).decode()
    for line in text.splitlines():
        fields = line.split()
        if len(fields) == 2 and fields[1].lstrip("*") == name:
            if re.fullmatch(r"[a-fA-F0-9]{64}", fields[0]):
                return fields[0].lower()
    raise ValueError(f"No valid SHA-256 for {name}")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--version", required=True)
    args = parser.parse_args()
    version = args.version.removeprefix("v")
    if not re.fullmatch(r"[0-9]+\.[0-9]+\.[0-9]+", version):
        parser.error("version must be a stable release such as v0.2.5")
    root = Path(__file__).resolve().parent.parent
    path = root / "Formula/flightbay.rb"
    if path.exists():
        old = re.search(r'version "([0-9.]+)"', path.read_text())
        if old and tuple(map(int, old[1].split("."))) > tuple(map(int, version.split("."))):
            raise ValueError("Refusing to replace a newer Homebrew version")
    base = f"https://github.com/tjorourke/flightbay/releases/download/v{version}"
    platforms = []
    for arch, condition in [("arm64", "on_arm"), ("amd64", "on_intel")]:
        archive = f"flightbay_{version}_darwin_{arch}.tar.gz"
        desk = f"flightbay-desk_{version}_darwin_{arch}.tar.gz"
        sha = checksum(f"{base}/checksums-flightbay.txt", archive)
        desk_sha = checksum(f"{base}/{desk}.sha256", desk)
        platforms.append(f'''  {condition} do
    url "{base}/{archive}"
    sha256 "{sha}"

    resource "flightbay-desk" do
      url "{base}/{desk}"
      sha256 "{desk_sha}"
    end
  end
''')
    formula = f'''# Generated by scripts/update-homebrew.py from published release checksums.
class Flightbay < Formula
  desc "Capture and investigate redacted Kubernetes snapshots"
  homepage "https://github.com/tjorourke/flightbay"
  version "{version}"
  license "Apache-2.0"

  depends_on :macos

{chr(10).join(platforms)}
  def install
    bin.install "flightbay"
    resource("flightbay-desk").stage {{ bin.install "flightbay-desk" }}
  end

  test do
    assert_match version.to_s, shell_output("#{{bin}}/flightbay version")
    assert_match version.to_s, shell_output("#{{bin}}/flightbay-desk version")
  end
end
'''
    path.parent.mkdir(exist_ok=True)
    path.write_text(formula)
    print(f"Updated {path.relative_to(root)} to {version}")


if __name__ == "__main__":
    main()
